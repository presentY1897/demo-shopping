-- 주문 항목의 요율은 **비어 있을 수 없다** (TASK-0079 R1).
--
-- 앞선 마이그레이션은 이 칸을 `NULL` 허용으로 만들고 「이 칸이 생기기 전에 만들어진
-- 주문은 전역 기본율로 읽는다」고 적었다. 그 읽기 규칙이 곧 **함정**이다 — 주문
-- 생성이 요율 쓰기를 빠뜨리는 날, 정산은 오류를 내지 않고 조용히 10% 로 계산한다.
-- R1 이 「누락 시 정산 배치가 오류로 중단」을 요구한 자리인데, 중단시키는 것보다
-- 애초에 그런 행이 저장되지 않게 하는 편이 낫다.
--
-- 이미 있는 행은 폴백과 같은 값으로 채운다. 그것이 지금까지의 동작이었으므로 이
-- 채움은 아무것도 바꾸지 않는다 — 다만 그 사실을 읽는 규칙이 아니라 **데이터**로
-- 옮긴다.
--
-- **기본값은 주지 않는다.** 주면 쓰기를 빠뜨린 코드가 조용히 10% 를 얻고, 그것은
-- 지금 없애려는 바로 그 함정이다.
UPDATE "OrderItem" SET "commissionRateBp" = 1000 WHERE "commissionRateBp" IS NULL;

ALTER TABLE "OrderItem" ALTER COLUMN "commissionRateBp" SET NOT NULL;
