-- 신고 처리 알림 (TASK-0091)
--
-- 신고는 사람이 **자기가 낸 것**이고, 그 결과를 알리지 않으면 신고 버튼이 아무 데도
-- 닿지 않는 버튼이 된다. 반려됐을 때가 특히 그렇다 — 「보고 아니라고 판단했다」는
-- 말이 도착하지 않으면 신고자는 아무 일도 안 일어났다고 읽는다.
--
-- 파일이 따로인 이유는 PostgreSQL 때문이다: `ALTER TYPE ... ADD VALUE` 로 더한 값은
-- **같은 트랜잭션 안에서 쓸 수 없고**, 마이그레이션 하나가 트랜잭션 하나다.
ALTER TYPE "NotificationType" ADD VALUE 'REPORT_HANDLED';
