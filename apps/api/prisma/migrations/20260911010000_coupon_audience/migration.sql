-- 쿠폰이 닿을 수 있는 그룹 (TASK-0073)
-- 이 쿠폰이 닿을 수 있는 그룹.
--
-- `issuedByUserId` 가 「누가 냈나」라면 이것은 **「누구에게 갈 수 있나」**다. 둘을
-- 나눈 이유는 값이 아니라 **비용**이다: 「데모가 낸 쿠폰인가」를 발행자나 스토어를
-- 조인해 물으면 코드 발급 한 번이 질의 세 개를 더 끌고 오고, 그 경로는 캠페인이
-- 두드리는 자리다 (`coupon-performance.spec.ts` A5 가 그 수를 센다).
--
-- 값은 발행 시점에 정해진다 — **만든 사람이 체험 계정이거나 대상 스토어가 체험
-- 계정의 것이면** `DEMO`. 그 뒤로는 이 칸 자체가 사실이고 아무것도 조인하지 않는다.
-- 사본이 아니라 파생값이라 어긋날 수 없다: `User.isDemo` 는 발급된 뒤 바뀌지 않고
-- (만료는 툼스톤을 남길 뿐이다), 발행자도 스토어도 쿠폰이 사는 동안 바뀌지 않는다.
--
-- 기본값이 `ALL` 인 것은 **이 컬럼이 생기기 전의 행**들 때문이다. 그것들은 전부
-- 실계정 관리자나 실계정 판매자가 낸 것이고, 그때까지의 동작이 그대로다.
CREATE TYPE "CouponAudience" AS ENUM ('ALL', 'DEMO');

ALTER TABLE "Coupon" ADD COLUMN "audience" "CouponAudience" NOT NULL DEFAULT 'ALL';
