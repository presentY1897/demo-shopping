-- 닿지 못한 승인에 이름을 준다 (TASK-0056 4.1 · D-220).
--
-- 승인 요청의 결말은 셋인데 상태에는 둘뿐이었다 — 답이 오지 않은 것이 거절과 같은
-- 칸에 들어갔고, `FAILED` 는 나가는 화살표가 없어 대사가 찾아내도 옮길 곳이 없었다.
--
-- `ALTER TYPE ... ADD VALUE` 는 **더하기만 한다.** 기존 행은 하나도 움직이지 않고,
-- 이 값을 쓰는 코드는 다음 배포가 들고 온다. 그래서 이 마이그레이션은 되돌릴 일이
-- 생겨도 안전하다 — 열거형에서 값을 빼는 것은 Postgres 가 지원하지 않지만, 쓰지
-- 않는 값이 남아 있는 것은 아무 해가 없다.
ALTER TYPE "PaymentStatus" ADD VALUE 'UNRESOLVED';
