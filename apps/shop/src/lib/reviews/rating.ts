/**
 * 100배 정수를 사람이 읽는 평점으로 (TASK-0084 F2).
 *
 * **계약에 부동소수가 없다.** `ratingSummarySchema.averageTimes100` 은 435 이고 그것이
 * 4.35 라는 뜻이다 — 평균을 정수로 나르면 반올림이 서버에서 한 번만 일어나고, 세 앱이
 * 각자 다른 자리에서 반올림해 「4.3」과 「4.4」를 나란히 그리는 일이 없다.
 *
 * 그래서 나누는 자리는 **여기 하나**여야 한다. 화면마다 `/ 100` 을 적으면 그 나눗셈이
 * 문서가 아니라 관습이 되고, 한 화면이 `.toFixed(2)` 로 적는 날 같은 상품의 평점이 두
 * 가지로 보인다. `packages/ui` 의 상품 카드가 같은 이유로 `ratingOf` 하나를 갖는다.
 */

/** 별 다섯 칸. 채운 수를 세는 쪽도, 빈 칸을 그리는 쪽도 이 값에서 온다. */
export const RATING_STARS = 5

/**
 * 「4.4」. 소수 한 자리인 것은 상품 카드·상세 배지와 같은 자리수여야 하기 때문이다.
 *
 * **정수로 반올림하고 정수로 조립한다.** `(435 / 100).toFixed(1)` 은 「4.3」이다 —
 * 4.35 를 이진 부동소수로 정확히 적을 수 없어 실제 값이 4.3499… 이고, `toFixed` 는
 * 그것을 내림한다. 화면은 멀쩡한 숫자를 하나 그리고 아무 검사도 실패하지 않으며,
 * 달라지는 것은 사람이 상품을 고르는 근거뿐이다. 이 저장소가 금액을 정수로만 다루는
 * 이유와 같은 이유이고(CLAUDE.md 6장), 평점도 계약이 이미 정수로 보내 준다.
 *
 * 리뷰가 하나도 없을 때도 「0.0」을 돌려준다 — 그 자리에 무엇을 그릴지는 화면이
 * `summary.count` 로 정한다. 여기서 `null` 을 만들면 「없음」이라는 판단이 두 곳으로
 * 갈라진다.
 */
export function ratingText(averageTimes100: number): string {
  const tenths = Math.round(averageTimes100 / 10)

  return `${String(Math.trunc(tenths / 10))}.${String(tenths % 10)}`
}

/**
 * 별 다섯 개 중 몇 개를 칠할 것인가.
 *
 * 반올림이다. 반내림이면 4.9가 별 넷이 되어 **숫자와 그림이 서로 다른 말**을 하고,
 * 그 그림 쪽만 보는 사람에게는 그것이 유일한 답이다. 계약이 0~500 으로 묶어 두므로
 * (`averageTimes100`) 여기에 상·하한을 다시 두지 않는다 — 닿지 않는 갈래는 검사가
 * 지날 수 없고, 지날 수 없는 갈래는 틀려도 아무도 모른다.
 */
export function filledStars(averageTimes100: number): number {
  return Math.round(averageTimes100 / 100)
}
